"""Task 5 - evaluate the four FINAL models on the test rows (used once) and assemble results/tables.md.

Run train_logistic.py and train_svm.py first. From the repo root:  python src/test_models.py
"""
import json
import os

import joblib
import numpy as np
import pandas as pd

from logistic import predict
from metrics import accuracy, confusion_matrix
from prepare import data_prep_table, prepare

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "results")
MODELS = os.path.join(RES, "models")


def md_table(df):
    cols = list(df.columns)
    lines = ["| " + " | ".join(map(str, cols)) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        lines.append("| " + " | ".join(str(v) for v in r.values) + " |")
    return "\n".join(lines)


def main():
    d = prepare()
    yte = d["yte"]

    theta_R = np.array(json.load(open(f"{MODELS}/logreg_r.json"))["theta"])
    theta_Q = np.array(json.load(open(f"{MODELS}/logreg_q.json"))["theta"])
    lin = joblib.load(f"{MODELS}/best_linear_svm.joblib")
    rbf = joblib.load(f"{MODELS}/best_rbf_svm.joblib")

    preds = {
        "Logistic regression, Set R": predict(d["R_te"], theta_R),
        "Logistic regression, Set Q": predict(d["Q_te"], theta_Q),
        f"Linear SVM (C={lin.C:g})": lin.predict(d["Ste"]),
        f"RBF SVM (C={rbf.C:g}, gamma={rbf.gamma:g})": rbf.predict(d["Ste"]),
    }
    rows = []
    for name, p in preds.items():
        cm = confusion_matrix(yte, p)
        assert cm.sum() == len(yte)               # entries must add up to the test size
        rows.append([name, f"{accuracy(yte, p):.4f}", cm[0, 0], cm[0, 1], cm[1, 0], cm[1, 1]])
    table4 = pd.DataFrame(rows, columns=["Model", "Accuracy", "TN", "False alarms", "Missed faults", "TP"])
    table4.to_csv(f"{RES}/table4_test.csv", index=False)
    table1 = data_prep_table(d)
    table1.to_csv(f"{RES}/table1_data_prep.csv", index=False)

    parts = [("Table 1 - Data preparation", table1),
             ("Table 2 - Logistic regression", pd.read_csv(f"{RES}/table2_logreg.csv")),
             ("Table 3 - SVM validation results", pd.read_csv(f"{RES}/table3_svm_validation.csv")),
             (f"Table 4 - Test results ({len(yte)} test rows)", table4),
             ("Table 5 - Learned theta (Set Q, standardised features)",
              pd.read_csv(f"{RES}/table5_theta_setQ.csv"))]
    with open(f"{RES}/tables.md", "w") as f:
        f.write("# Results tables\n\nGenerated by `src/test_models.py`.\n\n")
        for title, t in parts:
            f.write(f"## {title}\n\n{md_table(t.astype(str))}\n\n")

    print(table4.to_string(index=False))


if __name__ == "__main__":
    main()
